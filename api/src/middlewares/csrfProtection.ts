import { RequestHandler } from 'express'
import { Request, Response } from 'express'
import csrf from 'csrf'
import { drainBody } from './drainBody'

declare module 'express-session' {
  interface SessionData {
    csrfSecret?: string
  }
}

const csrfTokens = new csrf()

/**
 * CSRF tokens must be bound to the session they were minted for.
 *
 * The previous implementation minted ONE process-level secret at startup and
 * derived every token from it, so any token verified for any user/session -
 * a token harvested from an anonymous visit (the public GET / injects one
 * into the page) authenticated state-changing requests for any logged-in
 * browser. The `csrf` library supports per-session secrets directly
 * (`create(secret)` / `verify(secret, token)`); we keep a secret per express
 * session in `req.session` so a token from session A can never satisfy
 * session B.
 *
 * Desktop mode has no session store at all - `configureExpressSession` only
 * mounts the session middleware in server mode. A per-user in-memory secret
 * map keyed by the session id keeps desktop working while still isolating
 * sessions from each other.
 */
const desktopSecrets = new Map<string, string>()

const getSecret = (req: Request): string => {
  if (req.session) {
    if (!req.session.csrfSecret) {
      req.session.csrfSecret = csrfTokens.secretSync()
    }
    return req.session.csrfSecret
  }

  // Desktop mode (or any session-less request): one secret per session id,
  // generated on first use. Session ids are unique per visitor.
  const key = req.sessionID || 'anonymous'
  let secret = desktopSecrets.get(key)
  if (!secret) {
    secret = csrfTokens.secretSync()
    desktopSecrets.set(key, secret)
  }
  return secret
}

export const generateCSRFToken = (req: Request) =>
  csrfTokens.create(getSecret(req))

export const CSRF_COOKIE_NAME = 'XSRF-TOKEN'

/**
 * Hand the CSRF token to the browser as a cookie.
 *
 * It travels as a `Set-Cookie` header rather than in an inline `<script>` tag
 * in the page: an inline script requires `'unsafe-inline'` in the
 * Content-Security-Policy, which also permits any script an attacker manages
 * to inject. The browser stores the cookie from the header on its own, and
 * both readers pick it up unchanged - axios echoes it as the `X-XSRF-TOKEN`
 * request header, and `getPreProgramVariables` reads it server-side.
 *
 * Not httpOnly: the cookie exists to be read by the app's JavaScript.
 */
export const setCSRFCookie = (req: Request, res: Response) => {
  const allowedDomain = process.env.ALLOWED_DOMAIN?.trim()

  res.cookie(CSRF_COOKIE_NAME, generateCSRFToken(req), {
    httpOnly: false,
    maxAge: 86400 * 1000,
    sameSite: 'strict',
    path: '/',
    ...(allowedDomain ? { domain: allowedDomain } : {})
  })
}

/**
 * Drop the CSRF cookie.
 *
 * The token is only valid against the session that minted it (see getSecret),
 * so once that session is gone - or the caller turns out not to be
 * authenticated at all - the browser is holding a token that can produce
 * nothing but `Invalid CSRF token!` on the next state-changing request. A
 * login is the first of those, which is what sasjs/server#304 reported.
 *
 * Removing it is enough: the next `GET /` mints one bound to the session the
 * browser now has. Where the session is being REPLACED rather than lost, mint
 * a fresh token instead of clearing (see the logout routes) so the client does
 * not have to ask again.
 *
 * The options have to match setCSRFCookie's: a browser matches a clear against
 * the cookie's name, domain and path, and keeps a cookie whose clear does not
 * line up.
 */
export const clearCSRFCookie = (res: Response) => {
  const allowedDomain = process.env.ALLOWED_DOMAIN?.trim()

  res.clearCookie(CSRF_COOKIE_NAME, {
    httpOnly: false,
    sameSite: 'strict',
    path: '/',
    ...(allowedDomain ? { domain: allowedDomain } : {})
  })
}

export const csrfProtection: RequestHandler = async (req, res, next) => {
  if (req.method === 'GET') return next()

  // Reads the token from the following locations, in order:
  // req.body.csrf_token - typically generated by the body-parser module.
  // req.headers['csrf-token'] - the CSRF-Token HTTP request header.
  // req.headers['xsrf-token'] - the XSRF-Token HTTP request header.
  // req.headers['x-csrf-token'] - the X-CSRF-Token HTTP request header.
  // req.headers['x-xsrf-token'] - the X-XSRF-Token HTTP request header.
  //
  // The query string is deliberately NO LONGER accepted: a query-string token
  // is attacker-controllable in cross-site form/img/link requests (the
  // browser appends the full URL including ?csrf_token=... with no
  // preflight), which defeats the point of the check.

  const token =
    req.body?.csrf_token ||
    req.headers['csrf-token'] ||
    req.headers['xsrf-token'] ||
    req.headers['x-csrf-token'] ||
    req.headers['x-xsrf-token']

  if (!csrfTokens.verify(getSecret(req), token)) {
    // Drain before refusing. A session-authenticated upload reaches this
    // before multer, so the body can still be arriving - see drainBody.
    await drainBody(req)

    return res.status(400).send('Invalid CSRF token!')
  }
  next()
}
