import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { parse } from 'yaml'

/**
 * A route that can refuse a request has to say so.
 *
 * Every secured route can answer `401` and every route that takes a body can
 * answer `400` - the schema does it before the handler runs - but tsoa only
 * writes what the controller declares, so a new route arrives documenting its
 * happy path alone. That is not a tidiness problem: a consumer that builds on
 * the document (sasjs/api does, with a corpus pinned to it) either sends a
 * request the document said was fine, or answers a status the document never
 * mentioned, and the mismatch surfaces months later in a re-vendor round that
 * costs a release at each end.
 *
 * So this fails on a route whose refusals are undocumented. The entries below
 * are the routes that were already like that when the check went in; the list
 * only shrinks, and a stale entry is reported rather than failed, so pruning it
 * is housekeeping instead of a red build.
 */
const BASELINE_PATH = join(__dirname, 'documentRefusals.baseline.json')

const BASELINE = new Set<string>(
  JSON.parse(readFileSync(BASELINE_PATH, 'utf8'))
)

const METHODS = ['get', 'post', 'put', 'patch', 'delete']

const document = parse(
  readFileSync(join(__dirname, '../../../../public/swagger.yaml'), 'utf8')
) as any

/** `<method> <path> <status>` for every refusal the document leaves out. */
const undocumented = (): string[] => {
  const found: string[] = []

  for (const [path, operations] of Object.entries<any>(document.paths || {}))
    for (const [method, operation] of Object.entries<any>(operations))
      if (METHODS.includes(method)) {
        const responses = Object.keys(operation.responses || {})
        const route = `${method} ${path}`

        if (operation.security && !responses.includes('401'))
          found.push(`${route} 401`)
        if (operation.requestBody && !responses.includes('400'))
          found.push(`${route} 400`)
      }

  return found
}

describe('the document states what each route refuses', () => {
  const found = undocumented()

  // `UPDATE_BASELINE=1 npx jest documentRefusals` records today's state, so the
  // list is generated by the same code that judges it rather than by hand
  if (process.env.UPDATE_BASELINE)
    writeFileSync(BASELINE_PATH, `${JSON.stringify(found.sort(), null, 2)}\n`)

  it('documents a 401 wherever a route is secured, and a 400 wherever it takes a body', () => {
    const added = found.filter((entry) => !BASELINE.has(entry))

    // the message names the fix: a @Response() on the controller method
    expect(added).toEqual([])
  })

  it('keeps the baseline honest by naming what is no longer needed', () => {
    // not a failure on purpose: a re-vendor that fixes four routes should not
    // turn the build red before the list is pruned
    const stale = Array.from(BASELINE).filter((entry) => !found.includes(entry))

    if (stale.length)
      console.log(
        `documentRefusals: ${stale.length} baseline entr(ies) can be pruned:\n` +
          stale.map((entry) => `  ${entry}`).join('\n')
      )

    expect(Array.isArray(stale)).toBe(true)
  })
})
