/**
 * Writes src/utils/buildInfo.generated.ts from the environment, falling back to
 * git. Runs as part of `npm run initial`, so every `build`, `exe` and
 * `prestart` produces a file that names the release it came from.
 *
 * The release workflow resolves the next version with `semantic-release
 * --dry-run` BEFORE it builds the executables, and passes it here as
 * SASJS_SERVER_VERSION - the tag does not exist yet at that point, so `git
 * describe` alone would report the previous release.
 */
import { execSync } from 'child_process'
import fs from 'fs'
import path from 'path'

const OUT_FILE = path.join(
  __dirname,
  '..',
  'src',
  'utils',
  'buildInfo.generated.ts'
)

const fromGit = (command: string, fallback: string): string => {
  try {
    const output = execSync(command, {
      stdio: ['ignore', 'pipe', 'ignore']
    })
      .toString()
      .trim()

    return output || fallback
  } catch (error) {
    // No git available (inside a pkg snapshot, or an export of the source).
    return fallback
  }
}

const envValue = (name: string): string | undefined => {
  const value = process.env[name]

  return value && value.trim() ? value.trim() : undefined
}

const rawHash =
  envValue('SASJS_SERVER_GIT_HASH') ||
  fromGit('git rev-parse --short HEAD', 'unknown')
// CI passes the full 40-character SHA; the screen and support tickets want the
// short form, which is what `git rev-parse --short` gives locally.
const gitHash = rawHash.length > 12 ? rawHash.slice(0, 7) : rawHash
const version =
  envValue('SASJS_SERVER_VERSION') ||
  fromGit('git describe --tags --always --dirty', 'dev')
const buildDate =
  envValue('SASJS_SERVER_BUILD_DATE') || new Date().toISOString()

const contents = `// Generated by scripts/generateBuildInfo.ts. Do not edit by hand.
export const BUILD_INFO = {
  version: ${JSON.stringify(version)},
  gitHash: ${JSON.stringify(gitHash)},
  buildDate: ${JSON.stringify(buildDate)}
}
`

let current = ''

try {
  current = fs.readFileSync(OUT_FILE, 'utf8')
} catch (error) {
  // First run: nothing to compare against.
}

if (current === contents) {
  console.log(`buildInfo: unchanged (${version} ${gitHash})`)
} else {
  fs.writeFileSync(OUT_FILE, contents)
  console.log(`buildInfo: ${version} ${gitHash} built ${buildDate}`)
}
