/**
 * Writes src/utils/buildInfo.generated.ts from the environment, falling back to
 * git. Runs last in `npm run initial` - after `downloadMacros`, so the macros
 * release it records is the one the build installed rather than what an earlier
 * run in the same job recorded - and therefore before every `build`, `exe` and
 * `prestart` compiles anything that names the release it came from.
 *
 * The release workflow cuts the tag first and passes it here as
 * SASJS_SERVER_VERSION, because the executables are built from a checkout whose
 * `git describe` would otherwise risk reporting the previous release.
 *
 * Neither upstream value is configuration: the core version is read out of the
 * tree that was installed, and the macros release out of what `downloadMacros`
 * recorded, so both describe the build rather than what someone meant to build.
 */
import { execSync } from 'child_process'
import fs from 'fs'
import path from 'path'

import {
  SAS_PACKAGES_RELEASE,
  SAS_PACKAGES_RELEASE_SHA256,
  resolvedReleaseFile
} from '../scripts/downloadMacros'

const OUT_FILE = path.join(
  __dirname,
  '..',
  'src',
  'utils',
  'buildInfo.generated.ts'
)

const CORE_PACKAGE_FILE = path.join(
  __dirname,
  '..',
  'node_modules',
  '@sasjs',
  'core',
  'package.json'
)

const fromGit = (command: string, fallback: string): string => {
  try {
    const output = execSync(command, {
      stdio: ['ignore', 'pipe', 'ignore']
    })
      .toString()
      .trim()

    return output || fallback
  } catch (error) {
    // No git available (inside a pkg snapshot, or an export of the source).
    return fallback
  }
}

const envValue = (name: string): string | undefined => {
  const value = process.env[name]

  return value && value.trim() ? value.trim() : undefined
}

/** The version of the core macros that was installed, not the one requested. */
const coreVersion = (): string => {
  try {
    return JSON.parse(fs.readFileSync(CORE_PACKAGE_FILE, 'utf8')).version
  } catch (error) {
    return 'unknown'
  }
}

/**
 * The macros release the last download installed.
 *
 * A release build resolves the newest upstream tag, so the pin is only the
 * answer when nothing has been recorded yet - a fresh clone, or a build that
 * never ran `downloadMacros`.
 */
const sasPackages = (): { release: string; sha256: string; source: string } => {
  try {
    const recorded = JSON.parse(fs.readFileSync(resolvedReleaseFile, 'utf8'))

    return {
      release: recorded.tag,
      sha256: recorded.sha256,
      source: recorded.source
    }
  } catch (error) {
    return {
      release: SAS_PACKAGES_RELEASE,
      sha256: SAS_PACKAGES_RELEASE_SHA256,
      source: 'pinned'
    }
  }
}

const rawHash =
  envValue('SASJS_SERVER_GIT_HASH') ||
  fromGit('git rev-parse --short HEAD', 'unknown')
// CI passes the full 40-character SHA; the screen and support tickets want the
// short form, which is what `git rev-parse --short` gives locally.
const gitHash = rawHash.length > 12 ? rawHash.slice(0, 7) : rawHash
const version =
  envValue('SASJS_SERVER_VERSION') ||
  fromGit('git describe --tags --always --dirty', 'dev')
const buildDate =
  envValue('SASJS_SERVER_BUILD_DATE') || new Date().toISOString()
const core = coreVersion()
const macros = sasPackages()

const contents = `// Generated by scripts/generateBuildInfo.ts. Do not edit by hand.
export const BUILD_INFO = {
  version: ${JSON.stringify(version)},
  gitHash: ${JSON.stringify(gitHash)},
  buildDate: ${JSON.stringify(buildDate)},
  coreVersion: ${JSON.stringify(core)},
  sasPackages: {
    release: ${JSON.stringify(macros.release)},
    sha256: ${JSON.stringify(macros.sha256)},
    source: ${JSON.stringify(macros.source)}
  }
}
`

let current = ''

try {
  current = fs.readFileSync(OUT_FILE, 'utf8')
} catch (error) {
  // First run: nothing to compare against.
}

// Compare only what identifies the build. buildDate is part of the file but not
// of the identity, so including it in the check rewrote a committed file on
// every `npm run initial` (prestart, build, exe) and left a dirty working tree
// for developers and for the release job. The upstream values are identity:
// they change the macros a binary carries.
const field = (name: string) =>
  new RegExp(`${name}:\\s*"([^"]*)"`).exec(current)?.[1]

if (
  field('version') === version &&
  field('gitHash') === gitHash &&
  field('coreVersion') === core &&
  field('release') === macros.release &&
  field('sha256') === macros.sha256 &&
  field('source') === macros.source
) {
  console.log(`buildInfo: unchanged (${version} ${gitHash})`)
} else {
  fs.writeFileSync(OUT_FILE, contents)
  console.log(
    `buildInfo: ${version} ${gitHash} built ${buildDate} (core ${core}, macros ${macros.release} ${macros.source})`
  )
}
